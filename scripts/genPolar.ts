// Generates target speeds + optimal trim tables from the physics model.
// Re-run (npm run polar) after changing physics.ts or boatProfile.ts.
import { writeFileSync } from 'node:fs';
import { J80_PROFILE as P } from '../src/sim/boatProfile';
import { optimiseTrim, DEFAULT_PLAN, CONTROL_KEYS } from '../src/sim/physics';
const TWS = Array.from({ length: 26 }, (_, i) => i + 3); // 3..28
const JIB_TWA = Array.from({ length: 31 }, (_, i) => 30 + i * 5); // 30..180
const GEN_TWA = Array.from({ length: 17 }, (_, i) => 100 + i * 5); // 100..180
function table(twas: number[], headsail: 'jib' | 'gennaker', sym = false) {
  const v: number[][] = [];
  const c: number[][][] = [];
  for (const tws of TWS) {
    const rowV: number[] = []; const rowC: number[][] = [];
    let prev: any;
    for (const twa of twas) {
      const plan = { ...DEFAULT_PLAN, headsail, kiteSym: sym };
      const o = optimiseTrim(P, { tws, twa, sea: 0 }, plan, undefined);
      const o2 = prev ? optimiseTrim(P, { tws, twa, sea: 0 }, plan, prev) : o;
      const best = o2.result.v > o.result.v ? o2 : o;
      prev = best.controls;
      rowV.push(+best.result.v.toFixed(3));
      rowC.push(CONTROL_KEYS.map((k) => +best.controls[k].toFixed(3)));
    }
    v.push(rowV); c.push(rowC);
    process.stdout.write(sym ? 's' : headsail[0]);
  }
  return { v, c };
}
// smooth the optimal-control tables: many trims give near-identical speed, so the raw
// optimum is noisy between neighbouring cells. A 3x3 blur gives stable coaching references.
function smooth(t: { v: number[][]; c: number[][][] }) {
  const out = t.c.map((r) => r.map((x) => [...x]));
  for (let pass = 0; pass < 2; pass++) {
    const src = pass === 0 ? t.c : out.map((r) => r.map((x) => [...x]));
    for (let i = 0; i < src.length; i++) for (let j = 0; j < src[i].length; j++) for (let k = 0; k < src[i][j].length; k++) {
      let s = 0, w = 0;
      for (let di = -1; di <= 1; di++) for (let dj = -1; dj <= 1; dj++) {
        const a = src[i + di]?.[j + dj]; if (!a) continue;
        const ww = di === 0 && dj === 0 ? 2 : 1; s += a[k] * ww; w += ww;
      }
      out[i][j][k] = +(s / w).toFixed(3);
    }
  }
  t.c = out;
  return t;
}
// after the blur, climb from the blurred trim to the nearest optimum and store the speed THOSE
// controls reach: the coaching reference stays smooth, and the target is always what the
// "optimal" trim actually sails (a blur across a sharp optimum, e.g. crew weight in light air,
// otherwise leaves a trim that cannot reach its own target)
function refine(t: { v: number[][]; c: number[][][] }, twas: number[], headsail: 'jib' | 'gennaker', sym = false) {
  TWS.forEach((tws, i) => {
    twas.forEach((twa, j) => {
      const start = Object.fromEntries(CONTROL_KEYS.map((k, n) => [k, t.c[i][j][n]])) as any;
      const o = optimiseTrim(P, { tws, twa, sea: 0 }, { ...DEFAULT_PLAN, headsail, kiteSym: sym }, start);
      t.c[i][j] = CONTROL_KEYS.map((k) => +o.controls[k].toFixed(3));
      t.v[i][j] = +o.result.v.toFixed(3);
    });
    process.stdout.write('r');
  });
  return t;
}
const jib = refine(smooth(table(JIB_TWA, 'jib')), JIB_TWA, 'jib');
const gen = refine(smooth(table(GEN_TWA, 'gennaker')), GEN_TWA, 'gennaker');
const spi = refine(smooth(table(GEN_TWA, 'gennaker', true)), GEN_TWA, 'gennaker', true);
const out = `// AUTO-GENERATED by scripts/genPolar.ts — do not edit by hand.
export const POLAR = ${JSON.stringify({ tws: TWS, keys: CONTROL_KEYS, jib: { twa: JIB_TWA, ...jib }, gennaker: { twa: GEN_TWA, ...gen }, spinnaker: { twa: GEN_TWA, ...spi } })};
`;
writeFileSync('src/sim/polar.generated.ts', out);
console.log('\ndone');
